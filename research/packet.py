"""Offline decoder of the observed HTTP envelope, not a .cig generator.

No networking or device access. Accepts one complete packet, not an HTTP capture.
The meaning of byte 5 depends on the opcode and is deliberately left opaque.
"""
import argparse
import binascii
from dataclasses import dataclass
import hashlib
import json
from pathlib import Path
import struct

HEADER = struct.Struct('<IBBHI')
MAGIC = 0x35467891
MAX_PAYLOAD = 16 * 1024 * 1024


@dataclass(frozen=True)
class Packet:
    opcode: int
    code: int
    payload: bytes


def decode(data):
    if len(data) < HEADER.size:
        raise ValueError('Truncated header')
    magic, opcode, code, checksum, length = HEADER.unpack_from(data)
    if magic != MAGIC:
        raise ValueError('Unexpected packet magic')
    if length > MAX_PAYLOAD:
        raise ValueError('Payload exceeds the offline inspection limit')
    if len(data) != HEADER.size + length:
        raise ValueError('Payload length does not match the complete packet')
    payload = data[HEADER.size:]
    if binascii.crc_hqx(payload, 0) != checksum:
        raise ValueError('Payload CRC mismatch')
    return Packet(opcode, code, payload)


def processing_result(packet):
    """Read the length-prefixed result observed for response opcode 0xd1.

    Extracting an opaque result does not authenticate it or establish that an
    iPhone would accept it. No result is generated by this function.
    """
    if packet.opcode != 0xd1:
        raise ValueError('Not the observed processing-response opcode')
    if len(packet.payload) < 4:
        raise ValueError('Missing result length')
    length = struct.unpack_from('<I', packet.payload)[0]
    if length != len(packet.payload)-4:
        raise ValueError('Result length mismatch')
    return packet.payload[4:]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('packet', type=Path)
    args = parser.parse_args()
    with args.packet.open('rb') as stream:
        data = stream.read(MAX_PAYLOAD + HEADER.size + 1)
    packet = decode(data)
    summary = {'opcode': hex(packet.opcode), 'code': packet.code,
               'payload_bytes': len(packet.payload),
               'payload_sha256': hashlib.sha256(packet.payload).hexdigest(),
               'crc_valid': True}
    if packet.opcode == 0xd1:
        summary['opaque_result_bytes'] = len(processing_result(packet))
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
