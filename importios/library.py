"""Read a stable local copy of the phone catalogue. No remote write API is used."""
import asyncio
from contextlib import closing
import hashlib
import json
import math
from pathlib import Path
import sqlite3
import tempfile

from .version import VERSION
from .phone_paths import media_path

REMOTE_DB = '/iTunes_Control/iTunes/MediaLibrary.sqlitedb'
MAX_FILE = 128*1024*1024
MAX_TRACKS = 100_000
# Internal MediaLibrary.item.media_type on the observed iOS 27 schema.
# This is NOT MediaPlayer's public MPMediaTypeMusic (1 << 0).
# Evidence: research/LECTURA-MEDIA-TYPE.md, rustunes catalogue/sqlite.rs.
MUSIC_MEDIA_TYPE = 8


class LibraryError(Exception):
    def __init__(self, message, diagnostic=None):
        super().__init__(message)
        self.diagnostic = diagnostic or 'catalogue:LibraryError'


class CatalogueChanging(LibraryError):
    def __init__(self):
        super().__init__('Música está actualizando el catálogo. La lectura se detuvo porque aún no hay una copia estable.','catalogue:changing')


def connection_failure(error, stage):
    messages = {
        'modules': 'No se pudo cargar el componente de comunicación de esta versión.',
        'usb': 'No se pudo acceder al servicio USB de Apple. Que el sistema detecte el teléfono no confirma que ese servicio esté disponible para TUPAQ.',
        'lockdown': 'Se detectó el dispositivo, pero no se pudo abrir su conexión de confianza.',
        'trust': 'No se pudo validar la autorización existente del ordenador.',
        'afc': 'La conexión con el dispositivo se abrió, pero iOS no permitió abrir el servicio de archivos.',
        'catalogue': 'El servicio de archivos se abrió, pero no se pudo copiar o consultar el catálogo de Música.',
        'timeout': 'La lectura tardó demasiado y se interrumpió.',
    }
    kind = type(error).__name__
    detail = f'{stage}:{kind}'
    if isinstance(error, ModuleNotFoundError) and error.name:
        import re
        if re.fullmatch(r'[A-Za-z_][A-Za-z0-9_.]{0,120}', error.name):
            detail += ':'+error.name
    return LibraryError(messages.get(stage, 'La lectura no pudo completarse.')+
                        ' No se ha escrito en la biblioteca del teléfono.', detail)



def format_diagnostics(diagnostics):
    """Only counts/flags generated by our reader, never song or device metadata."""
    return f'TUPAQ {VERSION}\nDiagnóstico de lectura:\n'+json.dumps(diagnostics, ensure_ascii=True, sort_keys=True, indent=2)


def read_catalogue(path, diagnostics=None):
    """Query the local snapshot only, accepting the documented item/extra schema."""
    try:
        wal_path = Path(str(path)+'-wal')
        wal_present = wal_path.exists()
        wal_bytes = wal_path.stat().st_size if wal_present else 0
        with closing(sqlite3.connect(Path(path).resolve().as_uri()+'?mode=ro', uri=True)) as db:
            db.execute('PRAGMA query_only=ON')
            db.execute('PRAGMA trusted_schema=OFF')
            if db.execute('PRAGMA quick_check').fetchone() != ('ok',):
                raise LibraryError('La copia de la biblioteca no pasó la comprobación de integridad.')
            required = {'item': {'item_pid', 'media_type', 'item_artist_pid', 'album_pid'},
                        'item_extra': {'item_pid', 'title', 'total_time_ms'},
                        'item_artist': {'item_artist_pid', 'item_artist'},
                        'album': {'album_pid', 'album'}}
            layout = {}
            for table, columns in required.items():
                found = {row[1] for row in db.execute(f'PRAGMA table_info("{table}")')}
                layout[table] = found
                if not columns <= found:
                    raise LibraryError('La estructura de esta biblioteca todavía no es compatible con el lector.')
            if diagnostics is not None:
                groups = db.execute('''SELECT CASE WHEN typeof(media_type)='integer'
                    THEN media_type ELSE NULL END, COUNT(*) FROM item GROUP BY 1 LIMIT 33''').fetchall()
                diagnostics.update({
                    'source': 'iTunes_Control/iTunes/MediaLibrary.sqlitedb',
                    'database_bytes': Path(path).stat().st_size,
                    'wal_present': wal_present,
                    'wal_bytes': wal_bytes,
                    'schema_version': db.execute('PRAGMA user_version').fetchone()[0],
                    'music_type_code': MUSIC_MEDIA_TYPE,
                    'music_type_comparison': 'equal',
                    'wal_mode': db.execute('PRAGMA journal_mode').fetchone()[0] == 'wal',
                    'items_total': db.execute('SELECT COUNT(*) FROM item').fetchone()[0],
                    'music_items': db.execute('SELECT COUNT(*) FROM item WHERE media_type = ?', (MUSIC_MEDIA_TYPE,)).fetchone()[0],
                    'music_without_extra': db.execute('''SELECT COUNT(*) FROM item i
                        LEFT JOIN item_extra e ON e.item_pid=i.item_pid
                        WHERE i.media_type = ? AND e.item_pid IS NULL''', (MUSIC_MEDIA_TYPE,)).fetchone()[0],
                    'media_types': [{'type': kind, 'count': count} for kind, count in groups[:32]],
                    'media_types_truncated': len(groups) > 32,
                })
            locations = ('base_location_id' in layout['item'] and 'location' in layout['item_extra']
                and {'base_location_id','path'} <= {r[1] for r in db.execute('PRAGMA table_info(base_location)')})
            paths = ', bl.path, e.location' if locations else ', NULL, NULL'
            location_join = 'LEFT JOIN base_location bl ON bl.base_location_id=i.base_location_id' if locations else ''
            state_columns = {r[1] for r in db.execute('PRAGMA table_info(item_state)')}
            state_schema = {'item_pid','is_placeholder','is_library_added','has_non_purgeable_asset'} <= state_columns
            playback_columns = {r[1] for r in db.execute('PRAGMA table_info(item_playback)')}
            playback_schema = {'item_pid','audio_format'} <= playback_columns
            extra_fields = ', e.file_size' if 'file_size' in layout['item_extra'] else ', NULL'
            extra_fields += ', st.is_placeholder, st.is_library_added, st.has_non_purgeable_asset' if state_schema else ', NULL, NULL, NULL'
            extra_fields += ', pb.audio_format' if playback_schema else ', NULL'
            protected_local = state_schema and 'has_non_purgeable_subscription_protected_local_asset' in state_columns
            extra_fields += ', st.has_non_purgeable_subscription_protected_local_asset' if protected_local else ', NULL'
            playback_timing = playback_schema and {'duration','sample_rate'} <= playback_columns
            extra_fields += ', pb.duration, pb.sample_rate' if playback_timing else ', NULL, NULL'
            metadata_joins = (' LEFT JOIN item_state st ON st.item_pid=i.item_pid' if state_schema else '')
            metadata_joins += ' LEFT JOIN item_playback pb ON pb.item_pid=i.item_pid' if playback_schema else ''
            rows = db.execute('''SELECT i.item_pid, e.title, a.item_artist, b.album, e.total_time_ms'''+paths+', i.album_pid'+extra_fields+'''
                FROM item i LEFT JOIN item_extra e ON e.item_pid=i.item_pid
                LEFT JOIN item_artist a ON a.item_artist_pid=i.item_artist_pid
                LEFT JOIN album b ON b.album_pid=i.album_pid
                '''+location_join+metadata_joins+'''
                WHERE i.media_type = ? ORDER BY e.title, i.item_pid LIMIT ?''', (MUSIC_MEDIA_TYPE, MAX_TRACKS+1)).fetchall()
            if len(rows) > MAX_TRACKS:
                raise LibraryError('La biblioteca supera el límite de 100.000 canciones de esta versión.')
            binding={}
            if {'db_pid','primary_container_pid'} <= {r[1] for r in db.execute('PRAGMA table_info(db_info)')}:
                identities=db.execute('SELECT db_pid,primary_container_pid FROM db_info LIMIT 2').fetchall()
                if len(identities)==1 and all(type(v) is int and v!=0 for v in identities[0]):
                    binding=dict(library_database=identities[0][0],library_primary=identities[0][1])
            wire_map={}
            if {'item_pid','sync_id'} <= {r[1] for r in db.execute('PRAGMA table_info(item_store)')}:
                wire_map={str(pid):wire for pid,wire in db.execute('SELECT item_pid,sync_id FROM item_store')}
            tracks = []
            from .remote_artwork import catalogue_artwork
            artwork = catalogue_artwork(db)
            for pid, title, artist, album, ms, base, leaf, album_pid, size, placeholder, added, asset, codec, protected, frames, rate in rows:
                if any(value is not None and not isinstance(value, str) for value in [title, artist, album]):
                    raise LibraryError('El catálogo contiene metadatos de un tipo no admitido.')
                duration = float(ms or 0)/1000
                if not math.isfinite(duration):
                    raise LibraryError('El catálogo contiene una duración no válida.')
                tracks.append({'id': str(pid), 'title': title or 'Sin título', 'artist': artist or 'Sin artista',
                               'album': album or 'Sin álbum', 'duration': max(0, duration),**binding})
                if str(pid) in wire_map:tracks[-1]['library_wire']=wire_map[str(pid)]
                if duration<=0 and type(frames) in (int,float) and type(rate) in (int,float) and frames>0 and rate>0:
                    seconds=frames/rate
                    if math.isfinite(seconds) and 0<seconds<=7*86400:
                        tracks[-1].update(duration=seconds,duration_source='playback')
                if locations:
                    tracks[-1]['afc_path'] = media_path(base, leaf)
                if state_schema:
                    if any(type(value) is not int or value not in (0,1) for value in (placeholder,added,asset)):
                        tracks[-1]['is_local'] = False
                    else:
                        tracks[-1]['is_local'] = placeholder == 0 and added == 1 and (asset == 1 or (type(protected) is int and protected == 1))
                if type(size) is int and size > 0:
                    tracks[-1]['size'] = size
                    tracks[-1]['size_source'] = 'catalogue'
                if type(codec) is int and codec > 0:
                    from .library_fields import format_label
                    tracks[-1]['format_label'] = format_label(codec,tracks[-1].get('afc_path'))
                    tracks[-1]['format_source'] = 'catalogue'
                covers = [artwork[key] for key in ((str(pid),0),(str(album_pid),4)) if key in artwork]
                if covers:
                    tracks[-1]['artwork_paths'] = list(dict.fromkeys(covers))
            if diagnostics is not None:
                diagnostics['tracks_returned'] = len(tracks)
                diagnostics['location_schema'] = locations
                diagnostics['usb_audio_paths'] = sum(bool(t.get('afc_path')) for t in tracks)
                from .library_fields import local_tracks
                diagnostics['local_state_schema'] = state_schema
                diagnostics['local_tracks'] = len(local_tracks(tracks))
            return tracks
    except (sqlite3.Error, OSError, ValueError, TypeError) as error:
        raise LibraryError('No se pudo leer una copia válida de la biblioteca de Música.') from error


async def _copy_catalogue_once(afc, directory, missing_errors=(FileNotFoundError,), diagnostics=None):
    """Two consecutive identical db+WAL reads, always opening AFC in mode 'r'."""
    directory = Path(directory)
    fingerprints = []
    for pass_number in range(2):
        from .cancellation import checkpoint
        checkpoint()
        folder = directory/str(pass_number)
        folder.mkdir()
        current = {}
        for suffix in ['', '-wal']:
            remote = REMOTE_DB+suffix
            try:
                before = await afc.stat(remote)
            except missing_errors:
                if suffix:
                    current[suffix] = None
                    continue
                raise LibraryError('No se encontró la biblioteca de Música en el iPhone.')
            size = before.get('st_size', -1)
            if before.get('st_ifmt') != 'S_IFREG' or not isinstance(size, int) or not 0 <= size <= MAX_FILE:
                raise LibraryError('La biblioteca contiene un archivo de tamaño o tipo no admitido.')
            handle = await afc.fopen(remote, 'r')
            target = folder/('MediaLibrary.sqlitedb'+suffix)
            try:
                with target.open('xb') as output:
                    remaining = size
                    while remaining:
                        checkpoint()
                        block = await afc.fread(handle, min(1024*1024, remaining))
                        if not block or len(block) > remaining:
                            raise LibraryError('La copia de la biblioteca quedó incompleta.')
                        output.write(block)
                        remaining -= len(block)
            finally:
                await afc.fclose(handle)
            after = await afc.stat(remote)
            if any(before.get(key) != after.get(key) for key in ['st_size', 'st_mtime', 'st_ifmt']):
                raise CatalogueChanging()
            with target.open('rb') as stream:
                current[suffix] = hashlib.file_digest(stream, 'sha256').hexdigest()
        fingerprints.append(current)
    if fingerprints[0] != fingerprints[1]:
        raise CatalogueChanging()
    return read_catalogue(directory/'1'/'MediaLibrary.sqlitedb', diagnostics)


async def copy_catalogue(afc,directory,missing_errors=(FileNotFoundError,),diagnostics=None):
    import shutil
    import uuid
    from .cancellation import checkpoint
    directory=Path(directory)
    if any((directory/str(n)).exists() for n in (0,1)):
        raise LibraryError('La carpeta de lectura ya está ocupada.','catalogue:destination')
    for attempt in range(3):
        checkpoint()
        work=directory/('.reading-'+uuid.uuid4().hex);work.mkdir(mode=0o700)
        try:
            tracks=await _copy_catalogue_once(afc,work,missing_errors,diagnostics)
            # Both reads matched. Retain one coherent copy, not two identical archives.
            (work/'1').rename(directory/'1')
            if diagnostics is not None:diagnostics['catalogue_attempts']=attempt+1
            return tracks
        except CatalogueChanging:
            if attempt==2:raise
            await asyncio.sleep(.2*(attempt+1))
        finally:
            shutil.rmtree(work,ignore_errors=True)


async def _read_phone(diagnostics=None, device_info=None):
    stage = 'modules'
    try:
        from pymobiledevice3 import usbmux
        from pymobiledevice3.lockdown import create_using_usbmux
        from pymobiledevice3.services.afc import AfcService, AfcFileNotFoundError

        stage = 'usb'
        devices = [device for device in await usbmux.list_devices() if device.is_usb]
        if len(devices) != 1:
            raise LibraryError('Conecta un solo iPhone por USB y desbloquéalo para leer su biblioteca.', 'usb:device-count')
        stage = 'lockdown'
        lockdown = await create_using_usbmux(serial=devices[0].serial, connection_type='USB', autopair=False,
                                           label='TUPAQ')
        async with lockdown:
            if device_info is not None and isinstance(lockdown.all_values,dict):
                name = lockdown.all_values.get('DeviceName')
                if isinstance(name,str) and 0 < len(name)<=120 and not any(ord(c)<32 for c in name):
                    device_info['name'] = name
            stage = 'trust'
            # The pinned SDK validates existing trust and starts a session in
            # create_using_usbmux even with autopair=False. A second validation
            # sends StartSession again and iOS responds with SessionActive.
            if not lockdown.paired or not lockdown.session_id:
                raise LibraryError('No se encontró una autorización de confianza válida para TUPAQ. No restablezcas la confianza ni la biblioteca; copia el diagnóstico para revisarlo.', 'trust:missing-record')
            stage = 'afc'
            async with AfcService(lockdown) as afc:
                stage = 'catalogue'
                with tempfile.TemporaryDirectory(prefix='importios-library-') as directory:
                    tracks=await copy_catalogue(afc, directory, (FileNotFoundError, AfcFileNotFoundError), diagnostics=diagnostics)
                    from .presence import probe_files
                    from .devices import device_token
                    for track in tracks:track['_device_token']=device_token(devices[0].serial)
                    return await probe_files(afc,tracks,diagnostics)
    except LibraryError:
        raise
    except Exception as error:
        raise connection_failure(error, stage) from error


def read_phone_library(diagnostics=None, device_info=None):
    try:
        return asyncio.run(asyncio.wait_for(_read_phone(diagnostics,device_info), timeout=120))
    except LibraryError:
        raise
    except Exception as error:
        # Do not expose pairing records or device identifiers in UI diagnostics.
        raise connection_failure(error, 'timeout' if isinstance(error, TimeoutError) else 'inicio') from error
